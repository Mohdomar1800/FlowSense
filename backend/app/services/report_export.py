"""Render a report as a Markdown document (for downloading, sharing, or pasting into notes)."""

from app.models.report_log import ReportLog
from app.schemas.report import ReportData


def _duration(seconds: float) -> str:
    minutes = int(round(seconds / 60))
    hours, minutes = divmod(minutes, 60)
    return f"{hours}h {minutes:02d}m" if hours else f"{minutes}m"


def _escape(text: str) -> str:
    """Neutralize characters that would change the Markdown structure (user-entered intents and tags)."""
    for char in "\\`*_[]#|<>":
        text = text.replace(char, f"\\{char}")
    return text


def _change(current: float, previous: float) -> str:
    if not previous:
        return ""
    delta = (current - previous) / previous
    return f" ({delta:+.0%} vs previous)"


def report_filename(report: ReportLog) -> str:
    return f"flowsense-{report.report_type}-report-{report.period_start.isoformat()}.md"


def render_markdown(report: ReportLog) -> str:
    if report.data is None:  # reports from before structured data existed
        return f"# FlowSense {report.report_type} report\n\n{_escape(report.content)}\n"

    d = ReportData.model_validate(report.data)
    t, p = d.totals, d.previous
    kind = "Daily" if report.report_type == "daily" else "Weekly"
    lines = [
        f"# {kind} report: {_escape(d.title)}",
        "",
        _escape(d.summary),
        "",
        "## At a glance",
        "",
        "| | |",
        "|---|---|",
        f"| Focus time | {_duration(t.focus_seconds)}{_change(t.focus_seconds, p.focus_seconds)} |",
        f"| Sessions | {t.sessions} |",
        f"| Focus score | {f'{t.average_focus_score:.0f}' if t.average_focus_score is not None else '–'} |",
        f"| Distractions | {t.distractions}{_change(t.distractions, p.distractions)} |",
        f"| Time lost to distractions | {_duration(t.time_lost_seconds)} |",
    ]
    if d.goal_seconds:
        lines.append(f"| Daily goal ({_duration(d.goal_seconds)}) met | {d.days_goal_met} of {len(d.days)} days |")
    if d.on_task_share is not None:
        lines.append(f"| Screen time on task | {d.on_task_share:.0%} |")

    if d.highlights:
        lines += ["", "## Highlights", "", *[f"- {_escape(h)}" for h in d.highlights]]
    if d.top_distraction:
        td = d.top_distraction
        lost = f", {_duration(td.time_lost_seconds)} lost" if td.time_lost_seconds else ""
        lines += ["", "## Biggest distraction", "", f"{_escape(td.subject)}: {td.count} times{lost}."]
    if report.report_type == "weekly":
        lines += ["", "## By day", "", "| Day | Focus | Goal |", "|---|---|---|"]
        for day in d.days:
            label = f"{day.date.strftime('%a %b')} {day.date.day}"
            lines.append(f"| {label} | {_duration(day.focus_seconds)} | {'yes' if day.goal_met else ''} |")
    if d.tags:
        lines += [
            "",
            "## Focus by tag",
            "",
            *[f"- {_escape(tag.name)}: {_duration(tag.focus_seconds)}" for tag in d.tags],
        ]
    lines += [
        "",
        "## Goal for " + ("tomorrow" if report.report_type == "daily" else "next week"),
        "",
        _escape(d.next_goal),
    ]
    lines += ["", "---", f"Generated by FlowSense on {report.created_at.strftime('%Y-%m-%d %H:%M')} UTC.", ""]
    return "\n".join(lines)
